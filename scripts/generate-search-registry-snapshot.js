'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const TARGET = path.join(ROOT, 'assets/js/shared/kc-search-registry.generated.js');
const SOURCE_FILES = [
  'assets/js/features/create-post/kc-create-post.schema.js',
  'assets/js/features/create-post/kc-create-post.fields.js',
  'assets/js/shared/kc-search-fields.shared.js'
];

function normalizeSource(value) {
  return String(value || '').replace(/\r\n?/g, '\n');
}

function readSource(relativePath) {
  return normalizeSource(fs.readFileSync(path.join(ROOT, relativePath), 'utf8'));
}

function buildRegistry() {
  const Projector = require('../assets/js/shared/kc-search-fields.shared.js');
  const resolvers = {
    getCaronasCampusOptions: () => [],
    getCaronasFeatureOptions: () => [],
    getHousingRegionOptions: () => [],
    getHousingFeatureOptions: () => [],
    getLostFoundLocationOptions: () => [],
    getOpportunityAreaOptions: () => [],
    normalizeOpportunityTypeKey: (value) => String(value || '').replace(/s$/, '')
  };
  const context = { window: { _KCCreatePost: { resolvers } }, console };
  vm.createContext(context);
  vm.runInContext(readSource(SOURCE_FILES[0]), context);
  context.window._KCCreatePost.resolvers = resolvers;
  vm.runInContext(readSource(SOURCE_FILES[1]), context);
  return Projector.buildRegistry(context.window._KCCreatePost.schema, context.window._KCCreatePost.fields);
}

function sourceHash() {
  const hash = crypto.createHash('sha256');
  SOURCE_FILES.forEach((file) => {
    hash.update(file);
    hash.update('\0');
    hash.update(readSource(file));
    hash.update('\0');
  });
  return hash.digest('hex');
}

function generateSnapshot() {
  return {
    snapshotVersion: '1.0.0',
    sourceHash: sourceHash(),
    registry: JSON.parse(JSON.stringify(buildRegistry()))
  };
}

function generateSource() {
  const json = JSON.stringify(generateSnapshot());
  return `/* AUTO-GENERATED by scripts/generate-search-registry-snapshot.js. DO NOT EDIT. */\n` +
    `(function (root, factory) {\n` +
    `  if (typeof module !== 'undefined' && module.exports) module.exports = factory();\n` +
    `  else root.KCSearchFieldRegistrySnapshot = factory();\n` +
    `}(typeof window !== 'undefined' ? window : this, function () {\n` +
    `  'use strict';\n` +
    `  function deepFreeze(value) {\n` +
    `    if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;\n` +
    `    Object.keys(value).forEach(function (key) { deepFreeze(value[key]); });\n` +
    `    return Object.freeze(value);\n` +
    `  }\n` +
    `  return deepFreeze(${json});\n` +
    `}));\n`;
}

function checkSnapshot() {
  if (!fs.existsSync(TARGET)) return false;
  return fs.readFileSync(TARGET, 'utf8') === generateSource();
}

function main() {
  if (process.argv.includes('--check')) {
    if (!checkSnapshot()) {
      process.stderr.write('Search registry snapshot is stale. Run npm run generate:search-registry.\n');
      process.exitCode = 1;
      return;
    }
    process.stdout.write('Search registry snapshot is up to date.\n');
    return;
  }
  fs.writeFileSync(TARGET, generateSource(), 'utf8');
  process.stdout.write(`Generated ${path.relative(ROOT, TARGET)}\n`);
}

if (require.main === module) main();

module.exports = {
  SOURCE_FILES, TARGET, buildRegistry, checkSnapshot, generateSnapshot,
  generateSource, normalizeSource, sourceHash
};
